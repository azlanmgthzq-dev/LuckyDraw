// participantService.js — Participants via supabase-js (admin only, protected by RLS)
import { supabase, check } from './supabaseClient';

const participantService = {
    // All participants, winners first (by prize_order, winner_index), then by registration time.
    // Adds is_winner, prize_title, prize_order, winner_index like the old API.
    async getAll(eventId) {
        const rows = check(await supabase
            .from('participants')
            .select('*, draw_results ( winner_index, prizes ( title, prize_order ) )')
            .eq('event_id', eventId)
            .order('registered_at', { ascending: true }));

        const list = rows.map(({ draw_results, ...p }) => {
            const win = draw_results?.[0];
            return {
                ...p,
                is_winner: !!win,
                prize_title: win?.prizes?.title ?? null,
                prize_order: win?.prizes?.prize_order ?? null,
                winner_index: win?.winner_index ?? null,
            };
        });

        // Stable sort keeps registered_at order for ties
        return list.sort((a, b) =>
            (b.is_winner - a.is_winner) ||
            ((a.prize_order ?? Infinity) - (b.prize_order ?? Infinity)) ||
            ((a.winner_index ?? Infinity) - (b.winner_index ?? Infinity))
        );
    },

    async getCount(eventId) {
        // count is on the response itself, not in data
        const res = await supabase
            .from('participants')
            .select('*', { count: 'exact', head: true })
            .eq('event_id', eventId);
        check(res);
        return res.count ?? 0;
    },

    // Admin: add VIP. Not checked in yet — VIP checks in at /checkin/:eventId
    // with email + checkin_code (generated by the database).
    async preRegister(eventId, { name, phone, email }) {
        return check(await supabase
            .from('participants')
            .insert([{
                event_id: eventId,
                name,
                phone: phone || null,
                email: email || null,
                is_pre_registered: true,
                checked_in: false,
                is_eligible: true,
            }])
            .select()
            .single());
    },

    async addVIP(eventId, data) {
        return participantService.preRegister(eventId, data);
    },

    async checkIn(eventId, participantId) {
        return check(await supabase
            .from('participants')
            .update({ checked_in: true })
            .eq('id', participantId)
            .eq('event_id', eventId)
            .select()
            .single());
    },

    // Delete one participant (their draw_results / scripted_winners cascade)
    async deleteOne(eventId, participantId) {
        check(await supabase.from('participants').delete().eq('id', participantId).eq('event_id', eventId));
    },

    // Full reset: close open sessions, delete results, delete participants
    async deleteAll(eventId) {
        check(await supabase
            .from('draw_sessions')
            .update({ ended_at: new Date().toISOString() })
            .eq('event_id', eventId)
            .is('ended_at', null));
        check(await supabase.from('draw_results').delete().eq('event_id', eventId));
        check(await supabase.from('participants').delete().eq('event_id', eventId));
    },
};

export default participantService;
