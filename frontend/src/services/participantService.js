// participantService.js — Participants via supabase-js (admin only, protected by RLS)
import { supabase, check } from './supabaseClient';

const PHOTO_BUCKET = 'participant-photos';
const PHOTO_MAX_PX = 400; // big enough for the draw screen avatars, small enough to load 100+ fast

// Shrink + convert to JPEG in the browser. Falls back to the original file
// if the browser can't decode it (e.g. HEIC on some desktops).
async function toSmallJpeg(file) {
    try {
        const bitmap = await createImageBitmap(file);
        const scale = Math.min(1, PHOTO_MAX_PX / Math.max(bitmap.width, bitmap.height));
        const canvas = document.createElement('canvas');
        canvas.width = Math.round(bitmap.width * scale);
        canvas.height = Math.round(bitmap.height * scale);
        canvas.getContext('2d').drawImage(bitmap, 0, 0, canvas.width, canvas.height);
        bitmap.close?.();
        const blob = await new Promise(res => canvas.toBlob(res, 'image/jpeg', 0.85));
        return blob ?? file;
    } catch {
        return file;
    }
}

const participantService = {
    // All participants, winners first (by prize_order, winner_index), then by registration time.
    // Adds is_winner, prize_title, prize_order, winner_index like the old API.
    async getAll(eventId) {
        const rows = check(await supabase
            .from('participants')
            .select('*, draw_results ( winner_index, prizes ( title, prize_order ) )')
            .eq('event_id', eventId)
            .order('registered_at', { ascending: true }));

        const list = rows.map(({ draw_results, ...p }) => {
            const win = draw_results?.[0];
            return {
                ...p,
                is_winner: !!win,
                prize_title: win?.prizes?.title ?? null,
                prize_order: win?.prizes?.prize_order ?? null,
                winner_index: win?.winner_index ?? null,
            };
        });

        // Stable sort keeps registered_at order for ties
        return list.sort((a, b) =>
            (b.is_winner - a.is_winner) ||
            ((a.prize_order ?? Infinity) - (b.prize_order ?? Infinity)) ||
            ((a.winner_index ?? Infinity) - (b.winner_index ?? Infinity))
        );
    },

    async getCount(eventId) {
        // count is on the response itself, not in data
        const res = await supabase
            .from('participants')
            .select('*', { count: 'exact', head: true })
            .eq('event_id', eventId);
        check(res);
        return res.count ?? 0;
    },

    // Admin: add VIP. Not checked in yet — VIP checks in at /checkin/:eventId
    // with email + checkin_code (generated by the database).
    async preRegister(eventId, { name, phone, email }) {
        return check(await supabase
            .from('participants')
            .insert([{
                event_id: eventId,
                name,
                phone: phone || null,
                email: email || null,
                is_pre_registered: true,
                checked_in: false,
                is_eligible: true,
            }])
            .select()
            .single());
    },

    async addVIP(eventId, data) {
        return participantService.preRegister(eventId, data);
    },

    async checkIn(eventId, participantId) {
        return check(await supabase
            .from('participants')
            .update({ checked_in: true })
            .eq('id', participantId)
            .eq('event_id', eventId)
            .select()
            .single());
    },

    // Upload to participant-photos/{id}.jpg (replacing any old one) and save the public URL.
    async uploadPhoto(participantId, file) {
        if (!file.type.startsWith('image/')) throw new Error('Sila pilih fail gambar / Please choose an image file');
        const body = await toSmallJpeg(file);
        const path = `${participantId}.jpg`;

        check(await supabase.storage
            .from(PHOTO_BUCKET)
            .upload(path, body, { contentType: body.type || 'image/jpeg', upsert: true }));

        // Same path on every upload, so add a version to bust browser/CDN caches
        const { data } = supabase.storage.from(PHOTO_BUCKET).getPublicUrl(path);
        const photoUrl = `${data.publicUrl}?v=${Date.now()}`;
        console.log(`[photo] participant ${participantId} → ${photoUrl}`);

        return check(await supabase
            .from('participants')
            .update({ photo_url: photoUrl })
            .eq('id', participantId)
            .select()
            .single());
    },

    // Delete one participant (their draw_results / scripted_winners cascade)
    async deleteOne(eventId, participantId) {
        check(await supabase.from('participants').delete().eq('id', participantId).eq('event_id', eventId));
    },

    // Full reset: close open sessions, delete results, delete participants
    async deleteAll(eventId) {
        check(await supabase
            .from('draw_sessions')
            .update({ ended_at: new Date().toISOString() })
            .eq('event_id', eventId)
            .is('ended_at', null));
        check(await supabase.from('draw_results').delete().eq('event_id', eventId));
        check(await supabase.from('participants').delete().eq('event_id', eventId));
    },
};

export default participantService;
